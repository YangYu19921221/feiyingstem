/**
 * 生成音标教材 Excel 模板 —— 让老师照着填,不用猜格式
 *
 * ## 为什么必须有模板
 * 上传要求「每个工作表一小节、表内有 单词/音标 两列」,不给模板老师只能猜。
 * 更要紧的是**音标符号**:软键盘上只有 48 个音素,填了表里没有的符号
 * (比如用字母 a 代替 æ、用 : 代替 ː)那道题学生永远填不对。
 * 所以模板里必须附一张「可用音标总表」。
 *
 * ## 在浏览器里生成,不走后端
 * SheetJS 上传流程已经在用了,顺手写出去即可 —— 省一个端点、也省一次往返。
 */
import * as XLSX from 'xlsx';
import { PHONEME_GROUPS } from './ipaPhonemes';

/** 示例数据取自《飞鹰英语专用教材第1册》1—1,老师一眼能对上纸书 */
const SAMPLE_1 = [
  { 单词: 'bad', 音标: '[bæd]', 释义: '坏的' },
  { 单词: 'babe', 音标: '[beɪb]', 释义: '婴儿' },
  { 单词: 'cab', 音标: '[kæb]', 释义: '出租车' },
  { 单词: 'fee', 音标: '[fiː]', 释义: '费用' },
  { 单词: 'bed', 音标: '[bed]', 释义: '床' },
];

const SAMPLE_2 = [
  { 单词: 'cheese', 音标: '[tʃiːz]', 释义: '奶酪' },
  { 单词: 'face', 音标: '[feɪs]', 释义: '脸' },
  { 单词: 'add', 音标: '[æd]', 释义: '增加' },
];

/** 填表说明。放在第一个工作表,但**不会被当成小节导入**
 *  —— 导入时只认有「单词」+「音标」两列的表,这张没有,会自动跳过 */
const HOW_TO: string[][] = [
  ['音标教材填写说明'],
  [''],
  ['一、一个工作表 = 一小节'],
  ['  表名写成「1—1 拼读」这样,系统会自动认出小节编号 1—1。'],
  ['  ⚠️ 每节的编号必须唯一。「1—1 拼读」和「1—1 复习」会撞成同一个编号,'],
  ['     校验时会报错,改掉其中一个表名即可。'],
  [''],
  ['二、表内必须有「单词」和「音标」两列,「释义」可留空'],
  ['  列的顺序无所谓,表头写对就行(单词/音标/释义)。'],
  ['  只要有一列空着(单词或音标),那一行会被跳过,不会报错。'],
  [''],
  ['三、音标写法不用统一'],
  ['  [bæd]、/bæd/、bæd 都认;冒号会自动转成长音符(fi: → fiː);'],
  ['  g 会转成 ɡ、ei 会转成 eɪ。系统统一归一,不必手工改。'],
  [''],
  ['四、⚠️ 只能用下面那张表里的音标符号'],
  ['  学生答题时用的是软键盘,键盘上没有的符号他永远打不出来 ——'],
  ['  填了就是一道做不对的死题。常见错法:'],
  ['    用字母 a 代替 æ(a 不是音标符号)'],
  ['    用 e: 代替 ɜː'],
  ['    用 tS / dZ 代替 tʃ / dʒ'],
  ['  上传前点「先校验」,系统会把不合格的行逐条列出来,改好再传。'],
  [''],
  ['五、每个词至少要有一个元音'],
  ['  第二遍练习只挖元音那一格(元音才是拼读的关键),没有元音就没法出题。'],
  [''],
  ['六、整本要么全进要么全不进'],
  ['  有任何一行不合格,整本都不会导入 —— 不会留半本残缺教材在系统里。'],
  [''],
  ['———————— 可用音标总表(48 个,与学生软键盘完全一致)————————'],
];

export function downloadPhoneticTemplate(): void {
  const wb = XLSX.utils.book_new();

  // 说明表 + 音标总表拼在一起
  const rows = [...HOW_TO];
  for (const g of PHONEME_GROUPS) {
    rows.push([g.label, g.keys.join('  ')]);
  }
  rows.push(['']);
  rows.push(['注:重音符 ˈ 可以填,但不影响判分;学生答题时不用填它。']);
  const ws0 = XLSX.utils.aoa_to_sheet(rows);
  ws0['!cols'] = [{ wch: 12 }, { wch: 60 }];
  XLSX.utils.book_append_sheet(wb, ws0, '填写说明(勿删表头)');

  // 两个示例小节
  for (const [name, data] of [
    ['1—1 拼读', SAMPLE_1], ['1—2 拼读', SAMPLE_2],
  ] as [string, typeof SAMPLE_1][]) {
    const ws = XLSX.utils.json_to_sheet(data, { header: ['单词', '音标', '释义'] });
    ws['!cols'] = [{ wch: 14 }, { wch: 16 }, { wch: 20 }];
    XLSX.utils.book_append_sheet(wb, ws, name);
  }

  XLSX.writeFile(wb, '音标教材模板.xlsx');
}
