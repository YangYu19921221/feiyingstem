import { Children } from 'react';
import type { ReactNode } from 'react';

/** 标题和它下面第一块内容绑在一起不分页(html2pdf 不认标题上的 break-after: avoid,11-04 导出时标题常被留在页底) */
function withHead(head: ReactNode, children: ReactNode) {
  const [first, ...rest] = Children.toArray(children);
  return (
    <>
      <div style={{ breakInside: 'avoid', pageBreakInside: 'avoid' }}>{head}{first}</div>
      {rest}
    </>
  );
}

const Section = ({ no, title, id, children }: { no: string; title: string; id?: string; children: ReactNode }) => (
  <section id={id} className="mt-8">
    {withHead(
      <h2 className="mb-2.5 flex items-center gap-2 text-[19px] font-black text-slate-900">
        <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md bg-[#FF6B35] text-[13px] font-bold text-white">{no}</span>
        {title}
      </h2>,
      children,
    )}
  </section>
);

const Sub = ({ title, children }: { title: string; children: ReactNode }) => (
  <div className="mt-5">
    {withHead(<h3 className="mb-1.5 border-l-4 border-[#FFD23F] pl-2 text-[15.5px] font-black text-slate-900">{title}</h3>, children)}
  </div>
);

/** 界面上的入口: 灰底小块,一眼看出「这是要点的地方」。
 * 整块不折行(inline-block + nowrap): 折行的灰底在 PDF 截图里会画到文字上面(html2canvas 不认跨行的行内背景) */
const Path = ({ children }: { children: ReactNode }) => (
  <span className="mx-0.5 inline-block whitespace-nowrap rounded bg-slate-100 px-1.5 align-baseline text-[12.5px] font-semibold leading-[1.45] text-slate-800">
    {children}
  </span>
);

/** 一条流程: 编号 + 做什么 + 在哪儿点 */
const Steps = ({ items }: { items: Array<{ t: ReactNode; d?: ReactNode }> }) => (
  <ol className="mt-2 space-y-1.5">
    {items.map((s, i) => (
      <li key={i} className="flex gap-2.5" style={{ breakInside: 'avoid' }}>
        <span className="mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-[#FFF1E9] text-[11.5px] font-black text-[#c2451a]">{i + 1}</span>
        <div className="min-w-0 flex-1">
          <p className="font-semibold text-slate-900">{s.t}</p>
          {s.d && <p className="text-[12.5px] leading-5 text-slate-600">{s.d}</p>}
        </div>
      </li>
    ))}
  </ol>
);

const Tip = ({ title = '注意', children }: { title?: string; children: ReactNode }) => (
  <div className="mt-2.5 rounded-lg border-l-4 border-[#FF6B35] bg-[#FFF8F0] px-3 py-2" style={{ breakInside: 'avoid' }}>
    <p className="text-[12px] font-bold text-[#c2451a]">{title}</p>
    <div className="mt-0.5 text-[12.5px] leading-5 text-slate-700">{children}</div>
  </div>
);

/** 两列卡片:一行一个 flex 装两张,不用 grid */
const CardPairs = ({ items }: { items: Array<{ t: string; d: ReactNode }> }) => {
  const rows: Array<typeof items> = [];
  for (let i = 0; i < items.length; i += 2) rows.push(items.slice(i, i + 2));
  return (
    <div className="mt-2.5 space-y-2">
      {rows.map((row) => (
        <div key={row[0].t} className="flex gap-2" style={{ breakInside: 'avoid' }}>
          {row.map((c) => (
            <div key={c.t} className="flex-1 rounded-lg border border-slate-200 p-2.5">
              <p className="font-bold text-slate-900">{c.t}</p>
              <div className="mt-1 text-[12px] leading-5 text-slate-600">{c.d}</div>
            </div>
          ))}
          {row.length === 1 && <div className="flex-1" />}
        </div>
      ))}
    </div>
  );
};

const th = 'border border-orange-200 bg-[#FFF1E9] px-2 py-1.5 text-left font-bold text-slate-900';
const td = 'border border-orange-200 px-2 py-1.5 align-top';

/** 表格外面包一层 div 挂 breakInside(html2pdf 对 table 上的 break-inside 不生效) */
const Table = ({ head, rows }: { head: string[]; rows: ReactNode[][] }) => (
  <div className="mt-2.5" style={{ breakInside: 'avoid' }}>
    <table className="w-full border-collapse text-[12.5px] leading-5">
      <thead><tr>{head.map((h) => <th key={h} className={th}>{h}</th>)}</tr></thead>
      <tbody>
        {rows.map((r, i) => <tr key={i}>{r.map((c, j) => <td key={j} className={td}>{c}</td>)}</tr>)}
      </tbody>
    </table>
  </div>
);

